create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  cat text not null,
  title text not null,
  description text,
  lat double precision not null,
  lng double precision not null,
  status text not null default 'new' check (status in ('new', 'progress', 'done')),
  votes integer not null default 0,
  severity integer not null default 3 check (severity between 1 and 5),
  photo text,
  reported_on date not null default current_date,
  created_at timestamptz not null default now()
);

alter table public.reports enable row level security;

grant select on table public.reports to anon, authenticated;
grant insert, update, delete on table public.reports to authenticated;
grant usage, select on sequence public.reports_id_seq to authenticated;

drop policy if exists "Anyone can view reports" on public.reports;
create policy "Anyone can view reports"
on public.reports for select
using (true);

drop policy if exists "Signed in users can create reports" on public.reports;
create policy "Signed in users can create reports"
on public.reports for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can update their own reports" on public.reports;
create policy "Users can update their own reports"
on public.reports for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own reports" on public.reports;
create policy "Users can delete their own reports"
on public.reports for delete
to authenticated
using (auth.uid() = user_id);

create index if not exists reports_created_at_idx on public.reports (created_at desc);
create index if not exists reports_status_idx on public.reports (status);
